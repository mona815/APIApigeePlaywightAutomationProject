// API REGRESSION TESTS
// ============================================================

test.describe('ESAL API services (PreProd) - Automation Collection', () => {

    let api;


    // --------------------------------------------------------
    // Setup
    // --------------------------------------------------------

    test.beforeAll(async () => {

        if (!env('dpurl')) {
            return;
        }

        api = await request.newContext({
            baseURL: env('dpurl'),
            ignoreHTTPSErrors: env('ignorehttpserrors') === 'true'
        });

    });


    // --------------------------------------------------------
    // Cleanup
    // --------------------------------------------------------

    test.afterAll(async () => {

        if (api) {
            await api.dispose();
        }

    });


    // ========================================================
    // One test per Postman request, in the collection order
    // ========================================================

    for (const def of collection) {

        const waitMs = Number(process.env.ESAL_WAIT_MS ?? def.waitMs);

        test(
            `@regression @esal #${pad(def.n)} ${def.method} - ${def.name}`,
            async () => {

                test.setTimeout(60000 + waitMs);

                const missing = missingEnv(def);

                test.skip(
                    missing.length > 0,
                    `Set in .env: ${missing.map(name => `ESAL_${name}`).join(', ')}`
                );

                // Login requests create their own session
                const session = def.login
                    ? {}
                    : await getSession(api, def.section);

                // Pre-request script: setTimeout(function(){}, 15000)
                if (waitMs > 0) {
                    await sleep(waitMs);
                }

                const response = await sendRequest(api, def, session);

                await logResponse(response);

                expect(response.status()).toBe(def.expect);

                if (def.login) {

                    await saveSession(def, response, session);

                    expect(session.token).toBeTruthy();

                    sessions[def.n] = session;
                }

            }
        );

    }

});