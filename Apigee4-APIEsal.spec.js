import { test, expect, request } from '@playwright/test';
import { randomUUID } from 'node:crypto';
import { readFileSync, existsSync } from 'node:fs';
import { basename } from 'node:path';
import { collection } from './data/esal-collection.js';


/* =====================================================================
 *  ESAL API services PreProd Automation Collection
 *
 *  One test per request of the Postman collection (76 requests), in the
 *  original order. The requests live in ./data/esal-collection.js
 *  (generated from the collection - bodies, paths, headers, expected
 *  status codes).
 *
 *  Postman behaviour that is reproduced here
 *    - {{variables}}  -> read from .env as ESAL_<variableName>
 *                        (e.g. {{dpurl}} -> ESAL_dpurl)
 *    - pre-request    -> unique invoice numbers (GAZT_<uuid>, SADAD_<uuid> ...),
 *                        {{currentdate}}, 15 second wait before token checks
 *    - test scripts   -> status code assertion (200, or 400 for 3 requests)
 *    - login requests -> store token / refreshtoken / bearertoken
 *                        (CAS login, and OAuth login that returns the CAS
 *                         token in the "Payload" response header)
 *    - auth           -> Bearer {{token}} (CAS) or Bearer {{bearertoken}} (OAuth),
 *                        "jwttoken" header, Basic auth for the OAuth login
 * ===================================================================== */


// ============================================================
// Test Data
// ============================================================

const env = (name) => process.env[`ESAL_${name}`] || '';

// Values generated per request (Postman pre-request scripts)
const DYNAMIC_VARS = ['invoiceNumber', 'fasahinvoiceNumber', 'currentdate'];

// Values produced by the login requests (Postman globals)
const SESSION_VARS = ['token', 'refreshtoken', 'bearertoken', 'token1'];

// Minimal PDF used when no real attachment is configured (ESAL_attachmentfile)
const SAMPLE_PDF = [
    '%PDF-1.4',
    '1 0 obj<</Type/Catalog/Pages 2 0 R>>endobj',
    '2 0 obj<</Type/Pages/Kids[3 0 R]/Count 1>>endobj',
    '3 0 obj<</Type/Page/Parent 2 0 R/MediaBox[0 0 200 200]>>endobj',
    'trailer<</Root 1 0 R>>',
    '%%EOF'
].join('\n');

// One login session (tokens) per login request, shared by the requests after it
const sessions = {};

// Postman environment variables - they persist from one request to the next
// (e.g. request #35 reuses {{fasahinvoiceNumber}} generated by request #34)
const environment = {};


// ============================================================
// Helper Functions
// ============================================================

function pad(number) {

    return String(number).padStart(2, '0');
}


function today() {

    return new Date().toISOString().slice(0, 10);
}


function sleep(ms) {

    return new Promise(resolve => setTimeout(resolve, ms));
}


async function logResponse(response) {

    console.log('-----------------------------------');
    console.log('Status:', response.status());
    console.log('Body:', await response.text());
    console.log('-----------------------------------');
}


// Names of all {{variables}} used by a request
function usedVariables(def) {

    const text = JSON.stringify([def.path, def.headers, def.body]);

    return [...new Set([...text.matchAll(/\{\{(\w+)\}\}/g)].map(match => match[1]))];
}


// Variables that must be configured in .env for a request (and its login)
function missingEnv(def) {

    const loginDef = collection.find(item => item.n === def.section);

    const names = new Set(['dpurl']);

    for (const item of [def, loginDef]) {

        usedVariables(item)
            .filter(name => !DYNAMIC_VARS.includes(name) && !SESSION_VARS.includes(name))
            .forEach(name => names.add(name));

        if (item.auth === 'basic') {
            names.add('oauthclientid');
            names.add('oauthclientsecret');
        }
    }

    return [...names].filter(name => !env(name));
}


function buildVariables(def, session) {

    // Pre-request script: pm.environment.set("invoiceNumber", "GAZT_" + uuid)
    if (def.pre?.var) {
        environment[def.pre.var] = `${def.pre.prefix}${randomUUID()}`;
    }

    // Safety net when a worker restarted and the value of an earlier request is gone
    environment.invoiceNumber ??= `GAZT_${randomUUID()}`;
    environment.fasahinvoiceNumber ??= `FASAH_${randomUUID()}`;

    return {
        ...environment,
        currentdate: today(),
        token: session.token || '',
        refreshtoken: session.refreshtoken || '',
        bearertoken: session.bearertoken || '',
        // {{token1}} is an environment value in Postman - falls back to the session token
        token1: env('token1') || session.token || ''
    };
}


function resolve(text, variables, encode = false) {

    return text.replace(/\{\{(\w+)\}\}/g, (_, name) => {

        const value = variables[name] ?? env(name);

        return encode ? encodeURIComponent(value) : value;
    });
}


function resolveDeep(value, variables) {

    if (typeof value === 'string') {
        return resolve(value, variables);
    }

    if (Array.isArray(value)) {
        return value.map(item => resolveDeep(item, variables));
    }

    if (value && typeof value === 'object') {
        return Object.fromEntries(
            Object.entries(value).map(([key, item]) => [key, resolveDeep(item, variables)])
        );
    }

    return value;
}


function loadAttachment() {

    const file = env('attachmentfile');

    if (file && existsSync(file)) {
        return {
            name: basename(file),
            mimeType: 'application/pdf',
            buffer: readFileSync(file)
        };
    }

    return {
        name: `GAZT_${randomUUID()}.pdf`,
        mimeType: 'application/pdf',
        buffer: Buffer.from(SAMPLE_PDF)
    };
}


// Sends one collection request exactly as Postman would
async function sendRequest(api, def, session) {

    const variables = buildVariables(def, session);

    const headers = {};

    if (def.auth === 'bearer') {
        headers.Authorization = `Bearer ${variables[def.authVar]}`;
    }

    if (def.auth === 'basic') {
        const credentials = `${env('oauthclientid')}:${env('oauthclientsecret')}`;
        headers.Authorization = `Basic ${Buffer.from(credentials).toString('base64')}`;
    }

    for (const [key, value] of Object.entries(def.headers)) {
        headers[key] = resolve(value, variables);
    }

    const options = {
        method: def.method,
        headers
    };

    const body = def.body;

    if (body?.type === 'json') {
        headers['Content-Type'] = body.contentType;
        options.data = JSON.stringify(resolveDeep(body.json, variables));
    }

    if (body?.type === 'text') {
        headers['Content-Type'] = body.contentType;
        options.data = resolve(body.text, variables);
    }

    if (body?.type === 'none') {
        headers['Content-Type'] = body.contentType;
    }

    if (body?.type === 'multipart') {

        options.multipart = {};

        for (const field of body.fields) {
            options.multipart[field.key] = field.kind === 'file'
                ? loadAttachment()
                : resolve(field.value, variables);
        }
    }

    return api.fetch(resolve(def.path, variables, true), options);
}


// Login requests store the tokens (Postman: pm.globals.set)
async function saveSession(def, response, session) {

    if (def.saves === 'cas') {

        const body = await response.json();

        session.token = body.authorization.token;
        session.refreshtoken = body.refresh.token;
    }

    if (def.saves === 'oauth') {

        // OAuth login returns the CAS token in the "Payload" response header
        const payload = JSON.parse(response.headers()['payload']);

        session.token = payload.authorization.token;
        session.refreshtoken = payload.refresh.token;
        session.bearertoken = (await response.json()).access_token;
    }
}


// Logs in once per section (and again if the worker was restarted after a failure)
async function getSession(api, sectionNumber) {

    if (sessions[sectionNumber]) {
        return sessions[sectionNumber];
    }

    const loginDef = collection.find(item => item.n === sectionNumber);

    const session = {};

    const response = await sendRequest(api, loginDef, session);

    if (response.status() !== 200) {
        throw new Error(
            `Login request #${loginDef.n} (${loginDef.name}) failed: ` +
            `${response.status()} ${await response.text()}`
        );
    }

    await saveSession(loginDef, response, session);

    sessions[sectionNumber] = session;

    return session;
}


